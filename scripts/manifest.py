#!/usr/bin/env python3
"""Keep the vendored engine honest.

This repository ships a copy of the ``v2n`` package so that deploying it never
needs credentials to a private repository. Copies rot. ``MANIFEST.json`` records
the upstream commit and the hash of every file, which turns "it looks the same"
into a check that either passes or fails.

Hashes are computed over the bytes on disk, so they only mean something if the
working tree matches what a clone produces. That is why ``.gitattributes`` pins
``eol=lf``: without it a Windows checkout writes CRLF into a few files and every
clone suddenly "drifts".

    python scripts/manifest.py write                    # regenerate after a sync
    python scripts/manifest.py verify                   # CI: exit 1 on drift
    python scripts/manifest.py sync --from ../video2notes

``sync`` copies everything under ``v2n/`` and removes files that no longer exist
upstream, so a deleted module cannot linger here and keep being imported.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ENGINE = REPO / "engine"
PACKAGE = ENGINE / "v2n"
MANIFEST = ENGINE / "MANIFEST.json"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git(source: Path, *args: str) -> str:
    """Best-effort git query; an empty string means "not a checkout"."""
    try:
        out = subprocess.run(["git", "-C", str(source), *args], check=False,
                             capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return ""
    return out.stdout.strip() if out.returncode == 0 else ""


def files() -> list[Path]:
    return sorted(p for p in PACKAGE.rglob("*")
                  if p.is_file() and "__pycache__" not in p.parts)


def payload(source: Path | None) -> dict[str, object]:
    if source is not None:
        # Record the URL, not the path it happened to be checked out at: a
        # manifest is read by strangers, and a local path tells them nothing.
        commit = git(source, "rev-parse", "HEAD") or "unknown"
        origin = git(source, "remote", "get-url", "origin") or str(source)
        if origin.startswith("git@"):
            origin = "https://" + origin[4:].replace(":", "/", 1)
    else:
        previous = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else {}
        commit, origin = previous.get("commit", "unknown"), previous.get("from", "unknown")
    return {
        "package": "v2n",
        "from": origin,
        "commit": commit,
        "note": "Generated by scripts/manifest.py; do not edit by hand.",
        "files": {str(p.relative_to(ENGINE)).replace("\\", "/"):
                  {"sha256": sha256(p), "bytes": p.stat().st_size} for p in files()},
    }


def cmd_write(source: Path | None) -> int:
    data = payload(source)
    MANIFEST.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    print(f"wrote {MANIFEST.relative_to(REPO)}: {len(data['files'])} files "
          f"from {str(data['commit'])[:8]}")
    return 0


def cmd_verify() -> int:
    if not MANIFEST.exists():
        print("FAIL engine/MANIFEST.json is missing; run: python scripts/manifest.py write")
        return 1
    recorded = json.loads(MANIFEST.read_text(encoding="utf-8")).get("files") or {}
    actual = {str(p.relative_to(ENGINE)).replace("\\", "/"): sha256(p) for p in files()}
    problems: list[str] = []
    for name, info in recorded.items():
        if name not in actual:
            problems.append(f"missing   {name}")
        elif actual[name] != info["sha256"]:
            problems.append(f"modified  {name}")
    for name in sorted(set(actual) - set(recorded)):
        problems.append(f"untracked {name}")
    if problems:
        print("FAIL the vendored engine drifted from MANIFEST.json:")
        for line in problems:
            print("     " + line)
        print("     if the change is intended, re-run: python scripts/manifest.py write")
        return 1
    print(f"ok   {len(actual)} files match MANIFEST.json")
    return 0


def _blob(root: Path, rel: Path) -> bytes | None:
    """The bytes Git stores for ``rel``, or None when it is not tracked.

    The working tree is not the source of truth for a vendored copy. On Windows a
    checkout can hold CRLF while the index holds LF; copying the working tree
    then vendors bytes no clone will ever produce, and the manifest verifies on
    the machine that built it and fails on every other one. Reading the index
    costs nothing and removes that whole class of drift.
    """
    try:
        out = subprocess.run(["git", "-C", str(root), "show", f":{rel.as_posix()}"],
                             check=False, capture_output=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return out.stdout if out.returncode == 0 else None


def cmd_sync(source: Path) -> int:
    root = source.resolve()
    src = root / "v2n"
    if not (src / "mcp_server.py").exists():
        print(f"FAIL {src} does not look like the upstream package")
        return 1
    for old in files():
        old.unlink()
    for stale in PACKAGE.rglob("__pycache__"):
        shutil.rmtree(stale, ignore_errors=True)
    copied = 0
    for path in sorted(src.rglob("*")):
        if not path.is_file() or "__pycache__" in path.parts:
            continue
        rel = path.relative_to(src)
        dest = PACKAGE / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        # write_bytes, not copy2 + text mode: the manifest hashes these exact
        # bytes, and a newline translation here would make it self-invalidating.
        data = _blob(root, Path("v2n") / rel)
        dest.write_bytes(data if data is not None else path.read_bytes())
        copied += 1
    print(f"copied {copied} files from {src}")
    return cmd_write(root)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="manifest.py",
                                 description="Verify or refresh the vendored engine.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    w = sub.add_parser("write", help="regenerate MANIFEST.json from the current tree")
    w.add_argument("--from", dest="source", default=None, help="upstream checkout")
    sub.add_parser("verify", help="exit 1 if the vendored engine drifted")
    s = sub.add_parser("sync", help="re-copy v2n from an upstream checkout")
    s.add_argument("--from", dest="source", required=True)
    args = ap.parse_args(argv)

    if args.cmd == "write":
        return cmd_write(Path(args.source).resolve() if args.source else None)
    if args.cmd == "verify":
        return cmd_verify()
    return cmd_sync(Path(args.source))


if __name__ == "__main__":
    sys.exit(main())
